let activeProject = null;
let projectHistoryOpen = false;

function getProjectTags(project) {
  const tags = new Set([project.category]);

  if (project.category === "hard-surface" || project.category === "environment") {
    tags.add("realistic");
  }

  if (project.category === "stylization" || project.title === "Kiki") {
    tags.add("stylization");
  }

  if (project.category === "characters" || project.title === "Anime style Comic" || project.title === "Stylised Knight") {
    tags.add("characters");
  }

  if (project.title === "Samurai" || project.title === "Bigfoot characters") {
    tags.add("realistic");
  }

  return [...tags];
}

function renderGallery() {
  gallery.innerHTML = projects
    .map(
      (project, index) => `
        <article class="project-card ${project.featured ? "project-card-featured" : ""}" data-category="${project.category}" data-tags="${getProjectTags(project).join(" ")}" data-index="${index}" tabindex="0">
          <picture>
            ${project.mobileImage ? `<source media="(max-width: 640px)" srcset="${project.mobileImage}">` : ""}
            <img src="${project.image}" alt="${project.title}">
          </picture>
          <div class="project-info">
            <h3>${project.title}</h3>
          </div>
        </article>
      `
    )
    .join("");
}

function filterProjects(filter) {
  document.querySelectorAll(".project-card").forEach((card) => {
    const tags = (card.dataset.tags || card.dataset.category || "").split(" ");
    const match = filter === "all" || tags.includes(filter);
    card.classList.toggle("is-hidden", !match);
  });
}

function setActiveFilter(activeButton) {
  filterButtons.forEach((item) => {
    const isActive = item === activeButton;
    item.classList.toggle("active", isActive);
    item.setAttribute("aria-selected", String(isActive));
  });
}

function openProject(index, pushHistory = true) {
  activeProject = projects[index];
  modalTitle.textContent = activeProject.title;
  modalCategory.textContent = activeProject.label;
  modalDescription.textContent = activeProject.description;
  modal.classList.add("is-open");
  modal.setAttribute("aria-hidden", "false");
  document.body.classList.add("modal-open");
  renderProjectGallery();
  if (pushHistory) {
    history.pushState({ projectOpen: true }, "", window.location.href);
    projectHistoryOpen = true;
  }
  modalClose.focus();
}

function getProjectImages(project) {
  return project.images && project.images.length ? project.images : [project.image];
}

function renderProjectGallery() {
  if (!activeProject) return;

  const images = getProjectImages(activeProject);
  galleryCount.textContent = `${images.length} ${images.length === 1 ? "image" : "images"}`;
  const story = activeProject.story && activeProject.story.length
    ? `
      <section class="project-story" aria-label="Project description">
        <div class="project-story-kicker">${activeProject.storyLabel || activeProject.label}</div>
        <div class="project-story-body">
          ${activeProject.story.map((paragraph) => `<p>${paragraph}</p>`).join("")}
        </div>
      </section>
    `
    : "";

  modalGallery.innerHTML = story + images
    .map(
      (image, imageIndex) => `
        <figure class="project-render" id="project-image-${imageIndex}">
          <img src="${image}" alt="${activeProject.title} render ${imageIndex + 1}" loading="${imageIndex > 1 ? "lazy" : "eager"}">
        </figure>
      `
    )
    .join("");
  modalGallery.scrollTop = 0;
}

function closeProject(syncHistory = true) {
  if (syncHistory && projectHistoryOpen) {
    history.back();
    return;
  }

  modal.classList.remove("is-open");
  modal.setAttribute("aria-hidden", "true");
  document.body.classList.remove("modal-open");
  activeProject = null;
  projectHistoryOpen = false;
}

renderGallery();

const revealItems = document.querySelectorAll(".project-card, .section-head, .profile-layout, .contact > *");

if ("IntersectionObserver" in window) {
  const revealObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          revealObserver.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.14 }
  );

  revealItems.forEach((item) => revealObserver.observe(item));
} else {
  revealItems.forEach((item) => item.classList.add("is-visible"));
}

filterButtons.forEach((button) => {
  button.addEventListener("click", () => {
    setActiveFilter(button);
    filterProjects(button.dataset.filter);
  });
});

heroTagButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const filter = button.dataset.filter;
    const matchingFilter = [...filterButtons].find((item) => item.dataset.filter === filter);
    if (matchingFilter) setActiveFilter(matchingFilter);
    filterProjects(filter);
    document.querySelector("#work").scrollIntoView({ behavior: prefersReducedMotion ? "auto" : "smooth" });
  });
});

gallery.addEventListener("click", (event) => {
  const card = event.target.closest(".project-card");
  if (card) openProject(Number(card.dataset.index));
});

gallery.addEventListener("keydown", (event) => {
  const card = event.target.closest(".project-card");
  if (card && (event.key === "Enter" || event.key === " ")) {
    event.preventDefault();
    openProject(Number(card.dataset.index));
  }
});

